"""mutation_score.py [-k N] [-j J] [VIP ...] -- measure how well the functional
tests detect faults in the DUT models they test.

For each VIP, up to N mutants of its DUT model are generated by simple
operator and constant mutations, spread over the model (default N: 30 for
VIPs whose tests run on Icarus, 12 for Verilator-built ones, which take
~30 s per compile):

  * an integer literal N becomes N+1 (``0`` becomes ``1``)
  * ``==`` <-> ``!=``, ``&&`` <-> ``||``, ``1'b0`` <-> ``1'b1``
  * inside ``if``/``while``/``?:`` conditions: ``>`` <-> ``>=``, ``<`` <-> ``<=``
    and a ``!`` is dropped

Each mutant is run through every functional test of the VIP
(tools/run_func_tests.py). A mutant is *killed* when at least one test fails
(or hangs), *survives* when all tests still pass, and is *invalid* when it
does not compile. UVM VIPs mutate the flattened model
(``smoke/<VIP>/dut_<mod>.sv``); RTL IPs mutate ``rtl/*.sv``. Mutants are
written to ``build/mut/<VIP>/``; the sources are never modified.

A surviving mutant is either a gap in the tests or an equivalent mutant (no
observable change); the survivors are listed for review. Survivors reviewed
as equivalent or out of scope (e.g. tie-offs of a sibling protocol in a
shared model) are listed in ``tools/mutation_equivalent.csv``
(vip,location,mutation,reason); they are reported as ``equivalent`` and left
out of the score.

Output: one line per VIP and ``mutation_report.csv``
(vip,mutants,valid,killed,survived,equivalent,score,survivors) in the repo root.
"""
import os, re, sys, csv, glob, shutil, importlib.util
from multiprocessing import Pool

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MUT = os.path.join(ROOT, "build", "mut")
REPORT = os.path.join(ROOT, "mutation_report.csv")
EQUIV = os.path.join(ROOT, "tools", "mutation_equivalent.csv")

def equivalents():
    """{(vip, 'file:line', mutation): reason} of reviewed surviving mutants."""
    if not os.path.exists(EQUIV):
        return {}
    with open(EQUIV) as f:
        return {(r["vip"], r["location"], r["mutation"]): r["reason"]
                for r in csv.DictReader(l for l in f if not l.startswith("#"))}

_rf = None
def rf():
    global _rf
    if _rf is None:
        spec = importlib.util.spec_from_file_location("run_func_tests",
                                                      os.path.join(ROOT, "tools", "run_func_tests.py"))
        _rf = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(_rf)
    return _rf

SKIP_LINE = re.compile(r'^\s*(//|`|input\b|output\b|inout\b|import\b|typedef\b|module\b|endmodule\b|'
                       r'function\b|task\b|end(function|task|case)?\b\s*$)|\$display|\$sformatf|uvm_')

def mask(line):
    """Blank out comments, strings and [...] ranges (not mutated)."""
    line = re.sub(r'//.*', lambda m: " " * len(m.group(0)), line)
    line = re.sub(r'"[^"]*"', lambda m: " " * len(m.group(0)), line)
    return re.sub(r'\[[^\[\]]*\]', lambda m: " " * len(m.group(0)), line)

def cond_spans(line):
    """Character spans of if/while conditions and ?: selectors in a line."""
    spans = []
    for m in re.finditer(r'\b(if|while)\s*\(', line):
        depth, i = 1, m.end()
        while i < len(line) and depth:
            depth += {"(": 1, ")": -1}.get(line[i], 0)
            i += 1
        spans.append((m.end(), i - 1))
    q = line.find("?")
    if q > 0:
        spans.append((max(line.rfind("=", 0, q), line.rfind("(", 0, q)) + 1, q))
    return spans

def candidates(src):
    """(line_no, start, end, new_text, description) mutation candidates."""
    out = []
    lines = src.split("\n")
    body = False
    for n, line in enumerate(lines):
        if re.match(r'\s*module\b', line):
            body = True
        if not body or SKIP_LINE.search(line):
            continue
        m_line = mask(line)
        def add(s, e, new, what):
            out.append((n, s, e, new, what))
        for m in re.finditer(r"(?<![\w'.$])(\d+)(?![\w'.])", m_line):
            v = int(m.group(1))
            add(m.start(1), m.end(1), str(v + 1), "%d -> %d" % (v, v + 1))
        for m in re.finditer(r'(?<![=!<>])(==|!=)(?!=)', m_line):
            add(m.start(), m.end(), "!=" if m.group(1) == "==" else "==", m.group(1) + " flipped")
        for m in re.finditer(r'&&|\|\|', m_line):
            add(m.start(), m.end(), "||" if m.group(0) == "&&" else "&&", m.group(0) + " flipped")
        for m in re.finditer(r"1'b([01])", m_line):
            add(m.start(), m.end(), "1'b%d" % (1 - int(m.group(1))), "1'b%s inverted" % m.group(1))
        for s, e in cond_spans(m_line):
            seg = m_line[s:e]
            for m in re.finditer(r'(?<![<>=-])(>=|<=|>|<)(?![<>=])', seg):
                op = m.group(1)
                new = {">=": ">", ">": ">=", "<=": "<", "<": "<="}[op]
                add(s + m.start(1), s + m.end(1), new, "%s -> %s in condition" % (op, new))
            for m in re.finditer(r'!(?=[\w(])', seg):
                add(s + m.start(), s + m.end(), "", "! dropped in condition")
    return out

def pick(cands, k):
    """Up to k candidates spread evenly over the file."""
    if len(cands) <= k:
        return cands
    step = len(cands) / float(k)
    return [cands[int(i * step)] for i in range(k)]

def apply(src, c):
    lines = src.split("\n")
    n, s, e, new, _ = c
    lines[n] = lines[n][:s] + new + lines[n][e:]
    return "\n".join(lines)

def run_all(vip, tests, rtl_override):
    """'killed' / 'survived' / 'invalid' for the current (mutated) sources."""
    r = rf()
    results = []
    for tb, rtl in tests:
        files = rtl_override if rtl is not None else None
        st, sim, nchk, detail = r.run_test(vip, tb, files)
        results.append(st)
        if st == "FAIL":
            return "killed"
    if all(s == "PASS" for s in results):
        return "survived"
    return "invalid"

def mutate_vip(args):
    vip, k = args
    r = rf()
    run0 = r.run
    r.run = lambda cmd, cwd, timeout=300: run0(cmd, cwd, min(timeout, 240))   # hung mutant: killed
    tests = r.tests_of(vip)
    if not tests:
        return vip, 0, 0, 0, 0, 0, []
    wd = os.path.join(MUT, vip)
    shutil.rmtree(wd, ignore_errors=True)
    os.makedirs(wd)
    rtl = tests[0][1]
    if rtl is not None:
        targets = list(rtl)
    else:
        txt = "".join(open(tb, errors="ignore").read() for tb, _ in tests)
        flats = r.flat_modules(vip)
        targets = [flats[m] for m in flats if re.search(r'^\s*%s\b' % re.escape(m), txt, re.M)]
    # candidates over all target files, spread
    all_c = []
    for f in targets:
        src = open(f, errors="ignore").read()
        all_c += [(f, c) for c in candidates(src)]
    chosen = pick(all_c, k)
    orig_flat = r.flat_modules
    killed = survived = valid = equiv = 0
    surv = []
    eq = equivalents()
    for i, (f, c) in enumerate(chosen):
        mdir = os.path.join(wd, "m%02d" % i)
        os.makedirs(mdir)
        mfile = os.path.join(mdir, os.path.basename(f))
        open(mfile, "w").write(apply(open(f, errors="ignore").read(), c))
        if rtl is not None:
            rtl_files = [mfile if x == f else x for x in rtl]
            r.flat_modules = orig_flat
        else:
            rtl_files = None
            mapped = {m: (mfile if p == f else p) for m, p in orig_flat(vip).items()}
            r.flat_modules = lambda v, _m=mapped: _m
        verdict = run_all(vip, tests, rtl_files)
        r.flat_modules = orig_flat
        if verdict == "invalid":
            continue
        loc = "%s:%d" % (os.path.basename(f), c[0] + 1)
        if verdict == "survived" and (vip, loc, c[4]) in eq:
            equiv += 1
            continue
        valid += 1
        if verdict == "killed":
            killed += 1
        else:
            survived += 1
            line = open(f, errors="ignore").read().split("\n")[c[0]].strip()
            surv.append("%s %s [%s]" % (loc, c[4], line[:60]))
    return vip, len(chosen), valid, killed, survived, equiv, surv

def default_k(vip):
    rows = [r for r in csv.DictReader(open(rf().REPORT))] if os.path.exists(rf().REPORT) else []
    sims = {r["sim"] for r in rows if r["vip"] == vip}
    return 12 if "verilator" in sims else 30

def main(argv):
    k, jobs, names = None, 3, []
    it = iter(argv)
    for a in it:
        if a == "-k":
            k = int(next(it))
        elif a == "-j":
            jobs = int(next(it))
        else:
            names.append(a)
    r = rf()
    if not names:
        names = sorted(d for d in os.listdir(r.VIPS) if os.path.isdir(os.path.join(r.VIPS, d)))
    rows = []
    with Pool(jobs) as p:
        for vip, n, valid, killed, survived, equiv, surv in p.imap_unordered(mutate_vip, [(v, k or default_k(v)) for v in names]):
            score = (100.0 * killed / valid) if valid else 0.0
            rows.append((vip, n, valid, killed, survived, equiv, "%.0f" % score, " | ".join(surv)))
            print("MUT %s mutants=%d valid=%d killed=%d survived=%d equivalent=%d score=%.0f%%" % (
                vip, n, valid, killed, survived, equiv, score))
            for s in surv:
                print("    survived: " + s)
            sys.stdout.flush()
    rows.sort()
    if len(names) > 1:
        with open(REPORT, "w", newline="") as f:
            w = csv.writer(f)
            w.writerow(["vip", "mutants", "valid", "killed", "survived", "equivalent", "score", "survivors"])
            w.writerows(rows)
    return 0

if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
