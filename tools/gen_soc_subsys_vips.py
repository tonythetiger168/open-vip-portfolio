def test_plan(P, spec, tests):
    p = P.lower()
    src = open(os.path.join(SRC, "ip", f"{p}_tests.svh")).read()
    plan = re.search(r"/\*\s*TEST PLAN\s*(.*?)\*/", src, re.S)
    body = plan.group(1).strip() if plan else "(see the comments in the test classes)"
    return f"""# {P}-UVM-VIP test plan

## Register test (`{p}_ral_test`)

- ID reads the spec's code and version.
- `uvm_reg_hw_reset_seq`: every register that has a fixed reset value.
- `uvm_reg_bit_bash_seq`: every RW bit (IRQ_STATUS, core outputs and command
  pulses are left out: they are not plain storage).
- Random write + mirror check of every RW register.
- PSLVERR on the first unmapped word, on 0xFFC and on a misaligned address.

## AXI4 manager port (every test)

Checked on every burst by `axim_monitor` and `axim_if`: ID, INCR only, 4-byte
beats, 1..16 beats, no 4 KB crossing, aligned, full write strobes, WLAST /
RLAST position, one read and one write outstanding, address windows set per
job, responses matched to IDs, VALID/payload stability, no VALID in reset,
no X, every burst completes.

## Functional tests

{body}
"""


# ------------------------------------------------------------------ build
def copy_common(dst):
    os.makedirs(os.path.join(dst, "common"), exist_ok=True)
    for f in sorted(os.listdir(os.path.join(SRC, "common"))):
        shutil.copy(os.path.join(SRC, "common", f), os.path.join(dst, "common", f))


def write(path, txt):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w").write(txt)


def build_ip(P, spec, commit):
    p = P.lower()
    vip = f"{P}-UVM-VIP"
    dst = os.path.join(VIPS, vip)
    shutil.rmtree(dst, ignore_errors=True)
    copy_common(dst)
    # RTL snapshot
    mk = open(os.path.join(OIP, f"Makefile.{P}")).read()
    m = re.search(r"^DEPS[ \t]*:?=[ \t]*(.*)$", mk, re.M)
    deps = [os.path.basename(d) for d in (m.group(1).split() if m else [])]
    rtl_files = deps + [f"{P}_top.sv", f"{P}_apb.sv"]
    os.makedirs(os.path.join(dst, "rtl"), exist_ok=True)
    for f in rtl_files:
        shutil.copy(os.path.join(OIP, "rtl", f), os.path.join(dst, "rtl", f))
    write(os.path.join(dst, "rtl", "SNAPSHOT.txt"),
          f"open-ip-portfolio {commit}\nfiles: {' '.join(rtl_files)}\n"
          "Refresh with: OIP_DIR=<checkout> python3 tools/gen_soc_subsys_vips.py " + P + " --pack\n")
    # layout through open-ip-portfolio's generator
    core = gen_apb.core_ports(os.path.join(OIP, "rtl", f"{P}_top.sv"), f"{P}_top")
    words, irqb, flagb, _ = gen_apb.layout(spec, core[1], core[2])
    order, width, dirn, decl = wrapper(P)
    has_s = any(n.startswith("s_aw") for n in order)
    pins = other_pins(order, dirn)
    write(os.path.join(dst, p, f"{p}_ral.svh"), ral(P, spec, words, irqb, flagb))
    write(os.path.join(dst, p, f"{p}_pins_if.sv"), pins_if(P, pins, width, dirn))
    write(os.path.join(dst, p, f"{p}_pkg.sv"), pkg(P, spec, has_s))
    shutil.copy(os.path.join(SRC, "ip", f"{p}_tests.svh"), os.path.join(dst, p, f"{p}_tests.svh"))
    write(os.path.join(dst, "tb", "top_tb.sv"), top_tb(P, spec, order, width, dirn))
    tl = testlist(P)
    write(os.path.join(dst, "sim", f"{p}.f"), filelist(P, rtl_files, has_s))
    write(os.path.join(dst, "sim", "testlist.txt"),
          f"# {vip}: <test> <seeds> [plusargs]\n" + "\n".join(tl) + "\n")
    write(os.path.join(dst, "README.md"), readme(P, spec, words, irqb, tl, has_s, pins, commit))
    write(os.path.join(dst, "docs", "TEST_PLAN.md"), test_plan(P, spec, tl))
    print(f"{vip}: {len(words)} registers, {len(irqb)} irqs, pins {pins}, tests {[t.split()[0] for t in tl]}")
    return vip


def build_kit():
    dst = os.path.join(VIPS, KIT)
    shutil.rmtree(dst, ignore_errors=True)
    copy_common(dst)
    for d in ("tests", "tb", "docs"):
        if os.path.isdir(os.path.join(SRC, "kit", d)):
            shutil.copytree(os.path.join(SRC, "kit", d), os.path.join(dst, d))
    shutil.copy(os.path.join(SRC, "kit", "README.md"), os.path.join(dst, "README.md"))
    write(os.path.join(dst, "sim", "axim_kit.f"), "\n".join([
        "// AXI4_Manager_Port-UVM-VIP Verilator filelist (paths relative to the VIP root).",
        "// Before it: +incdir+$UVM_CORE $UVM_CORE/uvm_pkg.sv; top module: top_tb.",
        "+define+UVM_NO_DPI", "+incdir+common", "common/axim_if.sv", "common/ssv_apb_if.sv",
        "common/ssv_pkg.sv", "tests/axim_kit_pkg.sv", "tb/top_tb.sv", ""]))
    write(os.path.join(dst, "sim", "testlist.txt"),
          f"# {KIT}: <test> <seeds> [plusargs]\naxim_func_test 3\naxim_checker_test 1\nkit_if_rules_test 1\n")
    print(f"{KIT}: kit + self-test")
    return KIT


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    sp = specs()
    if "--all" in sys.argv or not args:
        args = [P for P, s in sp.items() if "axi_master" in s]
    commit = oip_commit()
    built = [build_kit()]
    for P in args:
        if P not in sp:
            raise SystemExit(f"no spec for {P} in {OIP}")
        if not os.path.exists(os.path.join(SRC, "ip", f"{P.lower()}_tests.svh")):
            print(f"{P}: no tools/soc_subsys/ip/{P.lower()}_tests.svh yet, skipped")
            continue
        built.append(build_ip(P, sp[P], commit))
    if "--pack" in sys.argv:
        subprocess.run(["bash", os.path.join(ROOT, "tools", "pack_vips.sh")] + built, check=True,
                       env=dict(os.environ, VIPS_DIR=VIPS))


if __name__ == "__main__":
    main()
