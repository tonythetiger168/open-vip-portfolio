"""gen_soc_subsys_vips.py [P ...] [--all] [--pack] -- build the SoC subsystem
UVM VIPs (and the AXI4 manager-port kit) from open-ip-portfolio.

For every IP whose spec scripts/apb/specs/<P>.json has an "axi_master"
section (or the IPs named on the command line), writes build/vips/<P>-UVM-VIP:

  common/          ssv_pkg (APB4 agent + RAL adapter, AXI4 manager-port
                   kit, env, base test) and the axim_if / ssv_apb_if
                   interfaces: copied from tools/soc_subsys/common
  rtl/             snapshot of the IP's RTL from open-ip-portfolio
                   (<P>_apb.sv, <P>_top.sv and the Makefile DEPS), with
                   SNAPSHOT.txt naming the commit
  <p>/<p>_ral.svh  register model, generated from the spec through
                   open-ip-portfolio's own scripts/apb/gen_apb.py layout(),
                   so every offset, field and reset value is the RTL's
  <p>/<p>_pkg.sv   package: register model, <p>_base_test (AXI contract
                   from the spec), <p>_ral_test, and the IP's functional
                   tests and reference model (tools/soc_subsys/ip/<p>_tests.svh)
  <p>/<p>_pins_if.sv  every wrapper pin that is not APB, irq or AXI
  tb/top_tb.sv     <P>_apb wired to the agents
  sim/<p>.f        Verilator filelist (paths relative to the VIP root;
                   add +incdir+$UVM_CORE and $UVM_CORE/uvm_pkg.sv first)
  sim/testlist.txt "<test> <seeds> [plusargs]"
  README.md, docs/TEST_PLAN.md

plus build/vips/AXI4_Manager_Port-UVM-VIP (the kit and its self-test).
--pack zips each tree into vips/<VIP>.zip (tools/pack_vips.sh).

Env: OIP_DIR (open-ip-portfolio checkout, default ../open-ip-portfolio),
     VIPS_DIR (default build/vips). Needs pyslang (gen_apb.py parses the RTL).
"""
import json, os, re, shutil, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "tools", "soc_subsys")
OIP = os.path.abspath(os.environ.get("OIP_DIR", os.path.join(ROOT, "..", "open-ip-portfolio")))
VIPS = os.environ.get("VIPS_DIR", os.path.join(ROOT, "build", "vips"))
HDR = "// Copyright 2026 VIP Portfolio Contributors\n// SPDX-License-Identifier: Apache-2.0\n"
KIT = "AXI4_Manager_Port-UVM-VIP"

sys.path.insert(0, os.path.join(OIP, "scripts", "apb"))
import gen_apb  # noqa: E402  (open-ip-portfolio's wrapper generator: the layout source of truth)

AXI_SIGS = ["awid", "awaddr", "awlen", "awsize", "awburst", "awprot", "awvalid", "awready",
            "wdata", "wstrb", "wlast", "wvalid", "wready", "bid", "bresp", "bvalid", "bready",
            "arid", "araddr", "arlen", "arsize", "arburst", "arprot", "arvalid", "arready",
            "rid", "rdata", "rresp", "rlast", "rvalid", "rready"]
APB_PINS = {"PCLK": None, "PRESETN": None, "PSEL": "psel", "PENABLE": "penable", "PWRITE": "pwrite",
            "PADDR": "paddr", "PWDATA": "pwdata", "PSTRB": "pstrb", "PRDATA": "prdata",
            "PREADY": "pready", "PSLVERR": "pslverr", "irq": "irq"}


def specs():
    d = os.path.join(OIP, "scripts", "apb", "specs")
    return {f[:-5]: json.load(open(os.path.join(d, f))) for f in sorted(os.listdir(d)) if f.endswith(".json")}


def oip_commit():
    try:
        return subprocess.run(["git", "-C", OIP, "rev-parse", "HEAD"], capture_output=True,
                              text=True).stdout.strip() or "unknown"
    except OSError:
        return "unknown"


def ident(s):
    return re.sub(r"\W", "_", s).strip("_")


# ------------------------------------------------------------------ RAL
def ral(P, spec, words, irqb, flagb):
    p = P.lower()
    code = int(spec["code"], 16)
    major, minor = (int(x) for x in spec.get("version", "1.0").split("."))
    idv = (code << 16) | (major << 8) | minor
    out = [HDR, f"// {p}_ral.svh -- register model of {P}_apb, generated by tools/gen_soc_subsys_vips.py",
           f"// from open-ip-portfolio scripts/apb/specs/{P}.json through gen_apb.layout(); do not edit.",
           "// Access types: rw -> RW (secret -> WO), ro -> RO (volatile), cmd -> WO pulse,",
           "// IRQ_STATUS -> W1C (volatile). Registers the core drives, command pulses and",
           "// IRQ_STATUS are kept out of the built-in reset / bit-bash sequences.", ""]
    regs = []
    for w in words:
        cls = f"{p}_reg_{ident(w.name).lower()}"
        fields, notest, nobash = [], False, False
        if w.kind == "id":
            fields = [("CODE", 16, 16, "RO", code, 0), ("MAJOR", 8, 8, "RO", major, 0), ("MINOR", 0, 8, "RO", minor, 0)]
        elif w.kind == "irq_status":
            fields = [(ident(n), i, 1, "W1C", 0, 1) for i, (n, _, _) in enumerate(irqb)]
            nobash = True
        elif w.kind == "irq_enable":
            fields = [(ident(n), i, 1, "RW", 0, 0) for i, (n, _, _) in enumerate(irqb)]
        elif w.kind == "flags":
            fields = [(ident(n), i, 1, "RO", 0, 1) for i, (n, _) in enumerate(flagb)] or [("RSVD", 0, 1, "RO", 0, 0)]
            notest = bool(flagb)
        elif w.kind == "scratch":
            fields = [("SCRATCH", 0, 32, "RW", 0, 0)]
        elif w.kind == "rw":
            acc = "WO" if w.secret else "RW"
            fields = [(ident(f.name), f.lo, f.w, acc, f.reset & ((1 << f.w) - 1), 0) for f in w.fields]
            nobash = w.secret
        elif w.kind == "ro":
            fields = [(ident(f.name), f.lo, f.w, "RO", 0, 1) for f in w.fields]
            notest = True
        elif w.kind == "cmd":
            fields = [(ident(f.name), f.lo, f.w, "WO", 0, 0) for f in w.fields]
            notest = True
        else:   # bus / stream words: the core decides what they do
            fields = [("DATA", 0, max(1, w.wb), "RW" if w.kind in ("bus", "sin") else "RO", 0, 1)]
            notest = True
        regs.append((w, cls, fields, notest, nobash))
        out += [f"class {cls} extends uvm_reg;", f"  `uvm_object_utils({cls})"]
        out += [f"  rand uvm_reg_field {fn};" for fn, *_ in fields]
        out += [f'  function new(string name = "{w.name}");', "    super.new(name, 32, UVM_NO_COVERAGE);",
                "  endfunction", "  virtual function void build();"]
        for fn, lo, wd, acc, rst, vol in fields:
            out.append(f'    {fn} = uvm_reg_field::type_id::create("{fn}");')
            out.append(f'    {fn}.configure(this, {wd}, {lo}, "{acc}", {vol}, {wd}\'h{rst:X}, 1, 1, 0);')
        out += ["  endfunction", "endclass", ""]
    blk = f"{p}_reg_block"
    out += [f"// {P}_apb: {len(words)} words at 0x000..0x{4 * len(words) - 4:03X}, ID 0x{idv:08X}",
            f"class {blk} extends uvm_reg_block;", f"  `uvm_object_utils({blk})"]
    out += [f"  rand {cls} {ident(w.name)};" for w, cls, *_ in regs]
    out += [f"  localparam bit [31:0] ID_VALUE = 32'h{idv:08X};",
            f'  function new(string name = "{blk}");', "    super.new(name, UVM_NO_COVERAGE);",
            "  endfunction", "  virtual function void build();",
            '    default_map = create_map("apb_map", 0, 4, UVM_LITTLE_ENDIAN, 1);']
    for w, cls, fields, notest, nobash in regs:
        n = ident(w.name)
        out += [f'    {n} = {cls}::type_id::create("{w.name}");', f"    {n}.configure(this);", f"    {n}.build();",
                f'    default_map.add_reg({n}, 12\'h{w.off:03X}, "{"RW" if any(a in ("RW", "W1C") for _, _, _, a, _, _ in fields) else ("WO" if all(a == "WO" for _, _, _, a, _, _ in fields) else "RO")}");']
        if notest:
            out.append(f'    uvm_resource_db #(bit)::set({{"REG::", {n}.get_full_name()}}, "NO_REG_TESTS", 1, this);')
        elif nobash:
            out.append(f'    uvm_resource_db #(bit)::set({{"REG::", {n}.get_full_name()}}, "NO_REG_BIT_BASH_TEST", 1, this);')
    out += ["  endfunction", "endclass", ""]
    return "\n".join(out)


# ------------------------------------------------------------------ pins
def wrapper(P):
    order, width, dirn, decl, params, _ = gen_apb.core_ports(os.path.join(OIP, "rtl", f"{P}_apb.sv"), f"{P}_apb")
    return order, width, dirn, decl


def other_pins(order, dirn):
    return [n for n in order if n not in APB_PINS and not re.match(r"[ms]_(%s)$" % "|".join(AXI_SIGS), n)]


def pins_if(P, pins, width, dirn):
    p = P.lower()
    out = [HDR, f"// {p}_pins_if.sv -- the {P}_apb pins that are neither APB, irq nor AXI",
           "// (generated by tools/gen_soc_subsys_vips.py). Inputs are driven by the tests",
           "// (0 after reset unless a test drives them), outputs are observed.", "",
           f"interface {p}_pins_if (input logic clk);"]
    for n in pins:
        w = width[n]
        out.append(f"  logic {'[%d:0] ' % (w - 1) if w > 1 else ''}{n};   // {dirn[n]} of {P}_apb")
    ins = [n for n in pins if dirn[n] == "input"]
    if ins:
        out.append("  initial begin")
        out += [f"    {n} = '0;" for n in ins]
        out.append("  end")
    out += ["endinterface", ""]
    return "\n".join(out)


def top_tb(P, spec, order, width, dirn):
    p = P.lower()
    pins = other_pins(order, dirn)
    has_s = any(n.startswith("s_aw") for n in order)
    conn = []
    for n in order:
        if n in ("PCLK", "PRESETN"):
            conn.append(f".{n}({'clk' if n == 'PCLK' else 'rstn'})")
        elif n in APB_PINS:
            conn.append(f".{n}(apb.{APB_PINS[n]})")
        elif n.startswith("m_") and n[2:] in AXI_SIGS:
            conn.append(f".{n}(axi.{n[2:]})")
        elif n.startswith("s_") and n[2:] in AXI_SIGS:
            conn.append(f".{n}(axs.{n[2:]})")
        else:
            conn.append(f".{n}(pins.{n})")
    out = [HDR, f"// top_tb.sv -- {P}-UVM-VIP testbench top (generated by tools/gen_soc_subsys_vips.py):",
           f"// open-ip-portfolio {P}_apb (rtl/ snapshot) with its APB4 port on the ssv APB agent,",
           "// its AXI4 manager port (m_*) on the kit's subordinate" +
           (", its AXI4 subordinate port (s_*) on the kit's manager BFM" if has_s else "") + ".",
           "//   +UVM_TESTNAME=<test> (sim/testlist.txt)", "",
           "module top_tb;", "  import uvm_pkg::*;", "  import ssv_pkg::*;", f"  import {p}_pkg::*;", "",
           "  logic clk = 1'b0;", "  logic rstn = 1'b0;",
           f"  always #{spec.get('tb_clk_ns', 10) // 2} clk = ~clk;",
           "  initial begin   // reset released on a falling edge: no race with the rising-edge logic",
           "    repeat (5) @(posedge clk);", "    @(negedge clk);", "    rstn = 1'b1;", "  end", "",
           "  ssv_apb_if apb (.pclk(clk), .presetn(rstn));",
           "  axim_if    axi (.aclk(clk), .aresetn(rstn));"]
    if has_s:
        out.append("  axim_if    axs (.aclk(clk), .aresetn(rstn));   // upstream manager -> s_*")
    out.append(f"  {p}_pins_if pins (.clk(clk));")
    out += ["", f"  {P}_apb dut (", "    " + ",\n    ".join(conn), "  );", "",
            "  initial begin",
            '    uvm_config_db #(virtual ssv_apb_if)::set(null, "*", "apb_vif", apb);',
            '    uvm_config_db #(virtual axim_if)::set(null, "*", "axim_vif", axi);']
    if has_s:
        out.append('    uvm_config_db #(virtual axim_if)::set(null, "*", "axim_s_vif", axs);')
    out += [f'    uvm_config_db #(virtual {p}_pins_if)::set(null, "*", "pins_vif", pins);',
            f'    run_test("{p}_ral_test");', "  end", "endmodule", ""]
    return "\n".join(out)


# ------------------------------------------------------------------ package
def pkg(P, spec, has_s):
    p = P.lower()
    am = spec["axi_master"]
    contract = [f"    c.expect_id  = {am['id']};" if not has_s else
                "    c.expect_id  = -1;   // forwarded bursts keep the upstream ID; walks use PTW_ID",
                f"    c.max_beats  = {am.get('max_burst', 16)};",
                # coverage declares only the bins this IP's contract can produce
                f"    c.cov_rd     = {int(am.get('reads', True))};",
                f"    c.cov_wr     = {int(am.get('writes', True))};"] + \
               ([] if has_s else [f"    c.cov_ids    = '{{{am['id']}}};"])
    return "\n".join([HDR,
        f"// {p}_pkg.sv -- {P}-UVM-VIP package (generated by tools/gen_soc_subsys_vips.py;",
        f"// the functional tests come from tools/soc_subsys/ip/{p}_tests.svh).",
        "", f"package {p}_pkg;", "  import uvm_pkg::*;", '  `include "uvm_macros.svh"', "  import ssv_pkg::*;", "",
        f'  `include "{p}_ral.svh"', "",
        f"  // {P}'s AXI4 manager contract (spec \"axi_master\" + notes): INCR, 4-byte beats,",
        "  // 1..16 beats, full strobes, aligned, no 4 KB crossing, one read and one write",
        "  // outstanding, the IP's own AXI ID.",
        f"  class {p}_base_test extends ssv_base_test;", f"    `uvm_component_utils({p}_base_test)",
        f"    virtual {p}_pins_if pins;",
        "    function new(string name, uvm_component parent);", "      super.new(name, parent);",
        f'      ip_name = "{P}";', "    endfunction",
        "    virtual function uvm_reg_block make_regmodel();",
        f'      {p}_reg_block b = {p}_reg_block::type_id::create("{p}_regs");',
        "      b.build();", "      return b;", "    endfunction",
        "    virtual function void configure_axi(axim_cfg c);"] + contract + [
        "    endfunction",
        "    function void build_phase(uvm_phase phase);", "      super.build_phase(phase);",
        f'      if (!uvm_config_db #(virtual {p}_pins_if)::get(this, "", "pins_vif", pins))',
        '        `uvm_fatal("NOVIF", "pins_vif not set")', "    endfunction", "  endclass", "",
        "  // register test: reset values, bit bash, write / mirror of every RW register,",
        "  // PSLVERR on unmapped and misaligned addresses. Prints RAL_PASS checks=<n>.",
        f"  class {p}_ral_test extends {p}_base_test;", f"    `uvm_component_utils({p}_ral_test)",
        "    function new(string name, uvm_component parent);", "      super.new(name, parent);", "    endfunction",
        "    task run_phase(uvm_phase phase);", "      bit [31:0] id;", "      phase.raise_objection(this);",
        "      wait_reset();", "      rd(\"ID\", id);",
        f"      check_eq(id, {p}_reg_block::ID_VALUE, \"ID\");", "      run_ral();", "      clocks(20);",
        "      phase.drop_objection(this);", "    endtask", "  endclass", "",
        f'  `include "{p}_tests.svh"', "endpackage", ""])


# ------------------------------------------------------------------ docs, lists
def testlist(P):
    """"<test> <seeds> [plusargs]" lines: the RAL test, then every
    "// testlist: <test> <seeds> [plusargs]" comment of the IP's test file."""
    p = P.lower()
    src = open(os.path.join(SRC, "ip", f"{p}_tests.svh")).read()
    return [f"{p}_ral_test 1"] + [m.strip() for m in re.findall(r"^//\s*testlist:\s*(.+)$", src, re.M)]


def filelist(P, rtl_files, has_s):
    p = P.lower()
    return "\n".join([f"// {P}-UVM-VIP Verilator filelist (paths relative to the VIP root).",
                      "// Before it: +incdir+$UVM_CORE $UVM_CORE/uvm_pkg.sv; top module: top_tb.",
                      "+define+UVM_NO_DPI", "+incdir+common", f"+incdir+{p}", "+incdir+tb"]
                     + [f"rtl/{f}" for f in rtl_files]
                     + ["common/axim_if.sv", "common/ssv_apb_if.sv", f"{p}/{p}_pins_if.sv", "common/ssv_pkg.sv",
                        f"{p}/{p}_pkg.sv", "tb/top_tb.sv", ""])


